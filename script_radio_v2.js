for (const entry of script) {
  const [text, opts] = entry;
  if (text === '') {
    children.push(blank());
    vrewLines.push('');
    continue;
  }
  if (text === 'H2') {
    children.push(h2(opts));
    continue; // Vrewには入れない
  }
  children.push(body(text, opts || {}));
  vrewLines.push(text);
}

